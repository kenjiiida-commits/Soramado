TYPE_MAP = {"OCl": "ocl", "GCl": "gcl", "PN": "pn", "SNR": "snr", "RfN": "rfn",
            "HII": "emn", "EmN": "emn", "Neb": "emn", "Cl+N": "emn", "*Ass": "ocl"}


def hms(s, hours):
    sign = -1 if s.strip().startswith("-") else 1
    parts = [float(x) for x in s.strip().lstrip("+-").split(":")]
    v = parts[0] + parts[1] / 60 + (parts[2] if len(parts) > 2 else 0) / 3600
    return sign * v * (15 if hours else 1)


def main(paths):
    rows = {}
    for p in paths:
        for r in csv.DictReader(open(p, encoding="utf-8"), delimiter=";"):
            rows[r["Name"]] = r
    out = []
    for name, (ja, ly, note) in OBJECTS.items():
        r = rows.get(name)
        if r is None:
            print("見つからない:", name, file=sys.stderr)
            continue
        typ = TYPE_MAP.get(r["Type"], "emn")
        if name in ("NGC6611", "NGC6618", "NGC6523", "NGC1976", "NGC3372", "NGC2237", "NGC1499",
                    "NGC7000", "IC1805", "NGC2264", "IC0434"):
            typ = "emn"
        if name in ("NGC6960", "NGC6992"):
            typ = "snr"
        if name == "NGC6888":
            typ = "emn"
        maj = float(r["MajAx"] or 0) or {"ocl": 10, "gcl": 8, "pn": 1, "emn": 20, "rfn": 5, "snr": 10}[typ]
        mnr = float(r["MinAx"] or 0) or maj
        common = (r.get("Common names") or "").split(",")[0].strip()
        label = f"M{int(r['M'])}" if r["M"] else (name[:3] + " " + name[3:].lstrip("0") if name[:3] in ("NGC", "IC0") else name)
        label = label.replace("IC0 ", "IC ").replace("IC0", "IC ")
        if name == "C041":
            common, label = "Hyades", "Mel 25"
        if name == "Mel022":
            common = "Pleiades"
        common = {"NGC6705": "Wild Duck Cluster", "NGC6618": "Omega Nebula", "NGC1976": "Orion Nebula",
                  "NGC0869": "Double Cluster (h Per)", "NGC0884": "Double Cluster (χ Per)",
                  "NGC5139": "Omega Centauri", "NGC0104": "47 Tucanae", "NGC3372": "Carina Nebula",
                  "IC0434": "Horsehead Nebula region", "NGC6960": "Veil Nebula (west)",
                  "NGC6992": "Veil Nebula (east)"}.get(name, common)
        name_en = f"{common} ({label})" if common else label
        out.append({
            "id": name, "name": ja, "name_en": name_en, "m": int(r["M"]) if r["M"] else 0, "type": typ,
            "ra": round(hms(r["RA"], True), 5), "dec": round(hms(r["Dec"], False), 5),
            "maj": maj, "min": mnr, "pa": float(r["PosAng"] or 0),
            "vmag": float(r["V-Mag"] or r["B-Mag"] or 0) or None, "ly": ly, "note": note,
            "const": r["Const"],
        })
    dest = Path(__file__).resolve().parent.parent / "soramado" / "data" / "nebulae.json"
    dest.write_text(json.dumps(out, ensure_ascii=False, indent=0), encoding="utf-8")
    print(len(out), "個 →", dest)


if __name__ == "__main__":
    main(sys.argv[1:])
